<?php

namespace Leaf\Llms;

use Leaf\Llms\Frameworks\Framework;

/**
 * Builds the files leafs/llms writes, from a detected project.
 */
class Generator
{
    protected Framework $framework;

    public function __construct(protected Project $project)
    {
        $this->framework = Framework::for($project);
    }

    public function framework(): Framework
    {
        return $this->framework;
    }

    /**
     * @return File[]
     */
    public function files(): array
    {
        $files = [
            new File('AGENTS.md', $this->agents()),
            new File('CLAUDE.md', $this->claude()),
            new File('llms.txt', $this->llms()),
            new File('.cursor/rules/project.mdc', $this->cursorProject(), $this->mdc(
                'Project overview, commands and conventions for ' . $this->project->name,
                null,
                true
            )),
            new File('.cursor/rules/php.mdc', $this->cursorPhp(), $this->mdc(
                $this->framework->label() . ' conventions for PHP files',
                '**/*.php',
                false
            )),
        ];

        foreach ($this->framework->skills() as $skill) {
            foreach (['.claude/skills', '.agents/skills'] as $dir) {
                $files[] = new File("$dir/{$skill->name}/SKILL.md", $skill->body, $skill->frontmatter());
            }
        }

        return $files;
    }

    protected function notice(): string
    {
        return '_Generated by [leafs/llms](https://github.com/leafsphp/llms). Re-run `vendor/bin/llms init` to refresh this section; anything outside the markers is yours and is kept._';
    }

    public function agents(): string
    {
        $p = $this->project;
        $f = $this->framework;
        $out = ['# ' . $p->name, ''];

        if ($p->description !== '') {
            $out[] = $p->description;
            $out[] = '';
        }

        $out[] = $this->notice();
        $out[] = '';

        if ($read = $f->readFirst()) {
            $out[] = '## Read first';
            $out[] = '';

            foreach ($read as $line) {
                $out[] = "- $line";
            }

            $out[] = '';
        }

        $out[] = '## Stack';
        $out[] = '';
        $out = [...$out, ...$this->stack(), ''];

        $out[] = '## Commands';
        $out[] = '';
        $out = [...$out, ...$this->commands(), ''];

        if ($layout = $this->layout()) {
            $out[] = '## Layout';
            $out[] = '';
            $out = [...$out, ...$layout, ''];
        }

        $out[] = '## Conventions';
        $out[] = '';

        foreach ($f->conventions() as $rule) {
            $out[] = "- $rule";
        }

        $out[] = '';
        $out[] = '## Before you finish';
        $out[] = '';
        $out = [...$out, ...$this->checklist(), ''];

        $out[] = '## Docs';
        $out[] = '';

        foreach ($f->docs() as $title => $url) {
            $out[] = "- [$title]($url)";
        }

        return implode("\n", $out);
    }

    /**
     * @return string[]
     */
    protected function stack(): array
    {
        $p = $this->project;
        $lines = [];

        if ($p->php !== '') {
            $lines[] = "- PHP `{$p->php}`";
        }

        $package = $this->framework->package();

        if ($package !== null && isset($p->packages[$package])) {
            $lines[] = "- {$this->framework->label()} (`$package` `{$p->packages[$package]}`)";
        } elseif ($package === null) {
            $lines[] = '- Plain PHP with Composer, no framework';
        }

        if ($p->testRunner !== null) {
            $lines[] = "- Tests: {$p->testRunner}";
        }

        foreach ($p->psr4 as $namespace => $path) {
            $lines[] = '- `' . rtrim($namespace, '\\') . "` lives in `$path`";
        }

        return $lines;
    }

    /**
     * @return string[]
     */
    protected function commands(): array
    {
        $labels = [
            'install' => 'Install',
            'test' => 'Test',
            'lint' => 'Lint',
            'format' => 'Format',
            'analyse' => 'Static analysis',
            'refactor' => 'Refactor check',
        ];
        $lines = [];
        $listed = [];

        foreach ($labels as $key => $label) {
            if ($command = $this->project->command($key)) {
                $lines[] = "- $label: `$command`";
                $listed[] = $command;
            }
        }

        foreach ($this->framework->cliCommands() as $label => $command) {
            $lines[] = "- $label: " . implode(', ', array_map(fn ($c) => "`$c`", (array) $command));
        }

        $scripts = array_diff($this->project->scripts, $listed);

        if ($scripts) {
            $lines[] = '- Composer scripts: ' . implode(', ', array_map(fn ($s) => "`$s`", $scripts));
        }

        return $lines;
    }

    /**
     * @return string[]
     */
    protected function layout(): array
    {
        $lines = [];

        foreach ($this->framework->directories() as $dir => $description) {
            if (is_dir($this->project->root . DIRECTORY_SEPARATOR . $dir)) {
                $lines[] = "- `$dir/`: $description";
            }
        }

        return $lines;
    }

    /**
     * @return string[]
     */
    protected function checklist(): array
    {
        $p = $this->project;
        $lines = [];

        if ($test = $p->command('test')) {
            $lines[] = "- Run `$test` and make sure it passes.";
        }

        $checks = array_filter([$p->command('lint'), $p->command('analyse')]);

        if ($checks) {
            $lines[] = '- Run ' . implode(' and ', array_map(fn ($c) => "`$c`", $checks)) . ' and fix what they report.';
        }

        $lines[] = '- Match the style of the code around your change, and keep the change focused on the task.';
        $lines[] = '- Do not edit `vendor/`, generated files or lock files by hand.';

        if ($p->hasPath('.leaf/CONTEXT.md')) {
            $lines[] = '- Update `.leaf/CONTEXT.md` with what changed.';
        }

        return $lines;
    }

    public function claude(): string
    {
        return implode("\n", [
            '@AGENTS.md',
            '',
            'AGENTS.md is the source of truth for this project. Skills live in `.claude/skills/`.',
        ]);
    }

    public function llms(): string
    {
        $p = $this->project;
        $f = $this->framework;
        $out = ['# ' . $p->name, ''];

        $summary = $p->description !== '' ? $p->description : "A {$f->label()} project.";
        $out[] = "> $summary";
        $out[] = '';
        $out[] = "Built with {$f->label()}" . ($p->php !== '' ? " on PHP `{$p->php}`" : '') . '. Agents should start with AGENTS.md.';
        $out[] = '';
        $out[] = '## Project';
        $out[] = '';
        $out[] = '- [AGENTS.md](AGENTS.md): stack, commands, layout and conventions';

        foreach (['README.md', 'README.MD', 'readme.md'] as $readme) {
            if ($p->hasPath($readme)) {
                $out[] = "- [README]($readme): what the project is and how to use it";

                break;
            }
        }

        $out[] = '- [composer.json](composer.json): dependencies and scripts';

        if ($p->hasPath('.leaf/CONTEXT.md')) {
            $out[] = '- [.leaf/CONTEXT.md](.leaf/CONTEXT.md): goals and architectural decisions';
        }

        $out[] = '';
        $out[] = '## Docs';
        $out[] = '';

        foreach ($f->docs() as $title => $url) {
            $out[] = "- [$title]($url)";
        }

        return implode("\n", $out);
    }

    protected function mdc(string $description, ?string $globs, bool $always): string
    {
        return implode("\n", [
            'description: ' . $description,
            'globs: ' . ($globs ?? ''),
            'alwaysApply: ' . ($always ? 'true' : 'false'),
        ]);
    }

    public function cursorProject(): string
    {
        return implode("\n", [
            '# ' . $this->project->name,
            '',
            'Read `AGENTS.md` at the project root before making changes. It lists the stack, the commands to run and the conventions to follow.',
            '',
            '## Commands',
            '',
            ...$this->commands(),
        ]);
    }

    public function cursorPhp(): string
    {
        $out = ['# ' . $this->framework->label() . ' conventions', ''];

        foreach ($this->framework->conventions() as $rule) {
            $out[] = "- $rule";
        }

        return implode("\n", $out);
    }
}
